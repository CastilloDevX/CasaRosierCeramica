const normalizeDate = (value: string) => new Date(value).getTime();

export const published: BlogPost[] = blogPosts
  .filter((post: BlogPost) => post.status === "published" && post.visibleInListing !== false)
  .sort((a, b) => normalizeDate(b.publishedAt) - normalizeDate(a.publishedAt) || (a.manualOrder ?? 0) - (b.manualOrder ?? 0));

export const categories = Array.from(new Set(published.map((post) => post.category)));

export const featured = blogPosts
  .filter((post) => post.status === "published" && post.isFeatured)
  .sort((a, b) => {
    if (typeof a.featuredOrder === "number" && typeof b.featuredOrder === "number") return a.featuredOrder - b.featuredOrder;
    return normalizeDate(b.publishedAt) - normalizeDate(a.publishedAt);
  });

export function bySlug(slug: string) {
  return blogPosts.find((post) => post.slug === slug) ?? null;
}

export function related(post: BlogPost, limit = 3) {
  return published.filter((item) => item.slug !== post.slug && item.category === post.category).slice(0, limit);
}

export function neighbors(post: BlogPost) {
  const index = published.findIndex((item) => item.slug === post.slug);
  return {
    previous: index > 0 ? published[index - 1] : null,
    next: index >= 0 && index < published.length - 1 ? published[index + 1] : null
  };
}
